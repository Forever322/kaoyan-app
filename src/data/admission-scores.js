// 将门类名 + 学位类型 + 可选专业映射为 ADMISSION_SCORES 中的 key
export function mapCategoryToScoreKey(category, degree, major) {
  const short = degree === 'xueshuo' ? '学硕' : '专硕';
  const exactKey = `${category}-${short}`;

  // Build candidate keys in priority order
  const keys = [];
  if (major && major !== '不限专业') {
    const majorName = major.replace(/\([^)]*\)/g, '').trim();
    keys.push(`${category}-${majorName}-${short}`);
  }
  keys.push(exactKey); // "工学-学硕" as fallback

  // Collect keys from ALL universities for fuzzy matching
  const allKeys = new Set();
  for (const uni of Object.values(ADMISSION_SCORES)) {
    for (const k of Object.keys(uni)) {
      allKeys.add(k);
    }
  }

  // Step 1: exact match in known keys
  for (const k of keys) {
    if (allKeys.has(k)) return k;
  }

  // Step 2: fuzzy match for the specific major
  if (major && major !== '不限专业') {
    const majorName = major.replace(/\([^)]*\)/g, '').trim();
    for (const k of allKeys) {
      if (k.endsWith(`-${short}`) && k.includes(majorName)) return k;
    }
  }

  // Step 3: fallback to exactKey (this will be used for estimation if not found)
  return exactKey;
}

/** 获取某院校某门类的历年录取分数。无真实数据时自动生成预估值 */
export function getAdmissionScores(universityName, category, degree, major) {
  const uni = ADMISSION_SCORES[universityName];
  const key = mapCategoryToScoreKey(category, degree, major);

  // 1. 优先使用真实数据
  if (uni) {
    const scores = uni[key];
    if (scores) {
      const years = ['2025', '2024', '2023', '2022'];
      const result = years
        .map((y) => ({ year: y, score: scores[y] || null }))
        .filter((item) => item.score !== null && item.score > 0);
      if (result.length > 0) return result;
    }
  }

  // 2. 无真实数据，自动生成预估值
  return generateEstimatedScores(universityName, category, degree);
}

// 根据院校层次和学科门类自动生成预估录取分数线
// 算法：基于该门类历年国家线 + 院校层次附加分（985顶尖+55~70, 985重点+35~50, 211+8~30, 双一流+3~12, 双非-5~+8）
export function generateEstimatedScores(universityName, category, degree) {
  const uni = findUniversity(universityName);
  if (!uni) return null;

  // 检查大学类型是否与该专业门类兼容
  if (!isCategoryCompatible(universityName, category)) return null;

  // 综合/师范/民族类双非零数据 → 不预估（无法确认专业方向）
  // 理工/农业/医药等专业型院校 → 即使零数据也生成预估（类型已表明专业方向）
  const hasRealData = !!ADMISSION_SCORES[universityName];
  if (!hasRealData && uni.level === '双非') {
    const uncertainTypes = ['综合', '师范', '民族'];
    if (uncertainTypes.includes(uni.type || '综合')) return null;
  }

  // 获取该门类A区国家线(作为基准)
  const nl = getAllYearLines(degree, category, 'A');
  if (nl.length === 0) return null;

  // 确定层次附加分
  const margin = getTierMargin(universityName, uni.level);

  // B区院校在国家线上减一些
  const zoneAdjust = uni.zone === 'B' ? -8 : 0;

  // 生成各年预估分
  return nl.map((n) => ({
    year: n.year,
    score: Math.max(0, n.score + margin + zoneAdjust),
  }));
}

