/**
 * 将门类名 + 学位类型映射为 ADMISSION_SCORES 中的 key
 * 因为 ADMISSION_SCORES 的 key 是简化的（如 "工学-学硕"），
 * 而 NATIONAL_LINES 的 key 可能是 "工学" 或 "电子信息/机械/..."
 */
function mapCategoryToScoreKey(category, degree) {
  const short = degree === 'xueshuo' ? '学硕' : '专硕';

  // 直接尝试拼接
  const directKey = `${category}-${short}`;
  // 检查是否有院校用了这个 key
  const allKeys = new Set();
  for (const uni of Object.values(ADMISSION_SCORES)) {
    for (const k of Object.keys(uni)) {
      allKeys.add(k);
    }
  }
  if (allKeys.has(directKey)) return directKey;

  // 模糊匹配: 尝试在所有 key 中找包含 category 且结尾匹配 short 的
  for (const k of allKeys) {
    if (k.endsWith(`-${short}`) && k.includes(category)) {
      return k;
    }
  }

  // 如果都没匹配到，返回 directKey（让调用方决定如何处理）
  return directKey;
}

/** 获取某院校某门类的历年录取分数 */
function getAdmissionScores(universityName, category, degree) {
  const uni = ADMISSION_SCORES[universityName];
  if (!uni) return null;

  const key = mapCategoryToScoreKey(category, degree);
  const scores = uni[key];

  if (!scores) return null;

  const years = ['2024', '2023', '2022'];
  return years
    .map(y => ({ year: y, score: scores[y] || null }))
    .filter(item => item.score !== null);
}

/** 更新或添加某院校某门类的录取分 */
function updateAdmissionScore(universityName, category, degree, year, score) {
  if (!ADMISSION_SCORES[universityName]) {
    ADMISSION_SCORES[universityName] = {};
  }
  const key = mapCategoryToScoreKey(category, degree);
  if (!ADMISSION_SCORES[universityName][key]) {
    ADMISSION_SCORES[universityName][key] = {};
  }
  ADMISSION_SCORES[universityName][key][year] = score;
}
