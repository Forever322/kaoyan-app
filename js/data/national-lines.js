/** 获取某类别、分区、年份的国家线 */
function getNationalLine(degree, category, zone, year) {
  const degData = NATIONAL_LINES[degree];
  if (!degData) return null;
  const catData = degData[category];
  if (!catData) return null;
  const zoneData = catData[zone];
  if (!zoneData) return null;
  return zoneData[String(year)] ?? null;
}

/** 获取所有可用年份的国家线 */
function getAllYearLines(degree, category, zone) {
  const years = ['2025', '2024', '2023', '2022'];
  return years
    .map(y => ({ year: y, score: getNationalLine(degree, category, zone, y) }))
    .filter(item => item.score && item.score > 0);
}

/** 获取最新年份的国家线 */
function getLatestNationalLine(degree, category, zone) {
  const years = ['2025', '2024', '2023', '2022'];
  for (const y of years) {
    const score = getNationalLine(degree, category, zone, y);
    if (score && score > 0) return { year: y, score };
  }
  return null;
}

/** 获取指定学位类型的所有门类列表 */
function getCategories(degree) {
  const degData = NATIONAL_LINES[degree];
  return degData ? Object.keys(degData) : [];
}

