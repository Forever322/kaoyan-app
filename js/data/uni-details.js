/** 获取院校详细信息，无数据时自动生成 */
function getUniversityDetail(universityName) {
  if (UNI_DETAILS[universityName]) {
    return UNI_DETAILS[universityName];
  }
  return generateDefaultDetail(universityName);
}

function generateDefaultDetail(name) {
  const uni = findUniversity(name);
  if (!uni) return null;

  const levelPros = [];
  const levelCons = [];
  const levelText = uni.level === '985' ? '985工程重点建设高校' : uni.level === '211' ? '211工程重点建设高校' : uni.level === '双一流' ? '双一流建设高校' : '省属重点建设高校';

  if (uni.level === '985') {
    levelPros.push('国家顶尖高校，社会认可度极高','科研经费充足','保研/深造比例高');
    levelCons.push('竞争激烈','考研难度大','录取分数线高');
  } else if (uni.level === '211') {
    levelPros.push('211重点大学','区域影响力强','就业有一定优势');
    levelCons.push('顶尖学科相对较少','部分211地理位置偏远');
  } else if (uni.level === '双一流') {
    levelPros.push('入选双一流建设名单','部分学科实力突出','发展潜力大');
    levelCons.push('整体知名度不如老牌985/211','社会认可度仍在建立中');
  } else {
    levelPros.push('部分特色专业实力较强','竞争压力相对较小','部分双非院校地理位置优越');
    levelCons.push('没有985/211头衔','部分用人单位有门槛限制','科研平台相对有限');
  }

  const zoneText = uni.zone === 'A' ? 'A区（教育资源较丰富区域）' : 'B区（国家线较低，录取相对容易）';
  levelPros.push(zoneText);

  return {
    pros: levelPros,
    cons: levelCons,
    features: `${name}位于${uni.province}${uni.city !== uni.province ? uni.city : ''}，是一所${levelText}。属于考研${uni.zone}区院校。`,
    color: '#' + Math.floor(Math.random()*16777215).toString(16).padStart(6, '0')
  };
}
